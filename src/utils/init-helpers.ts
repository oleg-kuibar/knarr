import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { consola } from "./console.js";
import { pc } from "./colors.js";
import { exists, ensureDir, atomicWriteFile } from "./fs.js";
import { detectJsonIndent, objectField, ownRecord, parseJsonObject } from "./json.js";
import { getConsumerStatePath, getConsumerKnarrDir } from "./paths.js";
import { readConsumerState, writeConsumerState } from "../core/tracker.js";
import type { PackageManager } from "../types.js";

/**
 * The committed hook. Teammates who don't use Knarr share it, so without
 * `.knarr/` (gitignored) it must be a silent no-op and never fail an install.
 * The real work lives in the local, generated `.knarr/restore.cjs`.
 */
export const POSTINSTALL_RESTORE_COMMAND =
  `node -e "try{require('./.knarr/restore.cjs')}catch(e){if(e.code!=='MODULE_NOT_FOUND')throw e}"`;

/**
 * Hook written by Knarr 0.1.x. It only worked with `knarr` on PATH, so after
 * `npx knarr use` every install silently dropped the links. Upgraded in place.
 */
export const LEGACY_POSTINSTALL_RESTORE_COMMAND = 'knarr restore --silent || node -e "process.exit(0)"';

export const RESTORE_SCRIPT_NAME = "restore.cjs";

export function usesLocalRestoreScript(postinstall: string): boolean {
  return postinstall.includes(`.knarr/${RESTORE_SCRIPT_NAME}`);
}

/**
 * Absolute path of the running Knarr CLI (`dist/cli.mjs`), or null when Knarr
 * runs from source (tests). Bundled chunks live next to cli.mjs in dist/.
 */
function currentCliPath(): string | null {
  const candidate = join(dirname(fileURLToPath(import.meta.url)), "cli.mjs");
  return existsSync(candidate) ? candidate : null;
}

/** Contents of the generated `.knarr/restore.cjs`. Exported for tests. */
export function renderRestoreScript(cliPath: string | null): string {
  return [
    "// Generated by Knarr. Re-applies Knarr-linked packages after an install.",
    "// Local only (.knarr/ is gitignored). knarr add, use, and restore rewrite it.",
    '"use strict";',
    'const { spawnSync } = require("node:child_process");',
    'const { existsSync } = require("node:fs");',
    "",
    `const cli = ${JSON.stringify(cliPath)};`,
    'const args = ["restore", "--silent"];',
    "const result = cli && existsSync(cli)",
    '  ? spawnSync(process.execPath, [cli, ...args], { stdio: "inherit" })',
    '  : spawnSync("knarr " + args.join(" "), { stdio: ["inherit", "inherit", "pipe"], shell: true });',
    "",
    "if (result.error || result.status !== 0) {",
    '  console.warn("[knarr] Linked packages were NOT restored after this install. Run: npx knarr restore");',
    "}",
    "",
  ].join("\n");
}

/** Write `.knarr/restore.cjs` for this consumer, pointing at the running CLI. */
export async function writeRestoreScript(projectDir: string): Promise<void> {
  const knarrDir = getConsumerKnarrDir(projectDir);
  await ensureDir(knarrDir);
  await atomicWriteFile(join(knarrDir, RESTORE_SCRIPT_NAME), renderRestoreScript(currentCliPath()));
}

export function usesSelfResolvingKnarrCommand(postinstall: string): boolean {
  return /\b(?:npx(?:\s+--yes|\s+-y)?|pnpm\s+dlx|yarn\s+dlx|bunx)\s+knarr\s+restore(?:\s|$)/.test(postinstall);
}

export function usesKnarrRestoreCommand(postinstall: string): boolean {
  if (usesLocalRestoreScript(postinstall)) return true;
  return /(?:^|[;&|()\s])(?:(?:npx(?:\s+(?:--yes|-y))?|pnpm\s+dlx|yarn\s+dlx|bunx)\s+)?knarr\s+restore(?:\s|$)/.test(postinstall);
}

function isStandaloneKnarrRestoreCommand(postinstall: string): boolean {
  const trimmed = postinstall.trim();
  return (
    trimmed === POSTINSTALL_RESTORE_COMMAND ||
    trimmed === LEGACY_POSTINSTALL_RESTORE_COMMAND ||
    trimmed === "knarr restore --silent" ||
    usesSelfResolvingKnarrCommand(trimmed)
  );
}

/**
 * Ensure .knarr/ is in .gitignore. Returns true if it was added.
 */
export async function ensureGitignore(
  gitignorePath: string,
): Promise<boolean> {
  let content = "";
  try {
    content = await readFile(gitignorePath, "utf-8");
  } catch {
    // .gitignore doesn't exist, create it
  }

  const lines = content.split("\n");
  const alreadyIgnored = lines.some(
    (line) =>
      line.trim() === ".knarr/" ||
      line.trim() === ".knarr" ||
      line.trim() === "/.knarr/" ||
      line.trim() === "/.knarr",
  );

  if (alreadyIgnored) return false;

  const separator =
    content.length > 0 && !content.endsWith("\n") ? "\n" : "";
  const section =
    content.length > 0
      ? "\n# knarr local links\n.knarr/\n"
      : "# knarr local links\n.knarr/\n";
  await atomicWriteFile(gitignorePath, content + separator + section);
  return true;
}

/**
 * Add a package-manager-neutral restore hook to package.json scripts, or
 * upgrade Knarr's legacy hook in place. Returns true if package.json changed.
 */
export async function addPostinstall(pkgPath: string): Promise<boolean> {
  const content = await readFile(pkgPath, "utf-8");
  const pkg = parseJsonObject(content, pkgPath);
  const indent = detectJsonIndent(content);
  const scripts = objectField(pkg, "scripts") ?? {};
  const existing = scripts["postinstall"];

  if (typeof existing === "string" && existing) {
    if (existing.includes(LEGACY_POSTINSTALL_RESTORE_COMMAND)) {
      scripts["postinstall"] = existing.replace(
        LEGACY_POSTINSTALL_RESTORE_COMMAND,
        POSTINSTALL_RESTORE_COMMAND
      );
      pkg["scripts"] = scripts;
      await atomicWriteFile(pkgPath, JSON.stringify(pkg, null, indent) + "\n");
      return true;
    }
    if (usesKnarrRestoreCommand(existing)) return false;
    consola.warn(
      `Existing postinstall script found. Add ${pc.cyan(POSTINSTALL_RESTORE_COMMAND)} manually if needed.`,
    );
    return false;
  }

  scripts["postinstall"] = POSTINSTALL_RESTORE_COMMAND;
  pkg["scripts"] = scripts;

  await atomicWriteFile(pkgPath, JSON.stringify(pkg, null, indent) + "\n");
  return true;
}

/**
 * Make installs re-apply links: (re)write `.knarr/restore.cjs` for the running
 * CLI, then add or upgrade the postinstall hook. Safe to call on every link.
 */
export async function ensureRestoreHook(projectDir: string): Promise<void> {
  await writeRestoreScript(projectDir);
  const pkgPath = join(projectDir, "package.json");
  if (await exists(pkgPath)) {
    await addPostinstall(pkgPath);
  }
}

/**
 * Remove the knarr postinstall script from package.json.
 * Returns true if it was removed.
 */
export async function removePostinstall(pkgPath: string): Promise<boolean> {
  let content: string;
  try {
    content = await readFile(pkgPath, "utf-8");
  } catch {
    return false;
  }
  const pkg = parseJsonObject(content, pkgPath);
  const scripts = objectField(pkg, "scripts");
  const postinstall = scripts?.["postinstall"];
  if (!scripts || typeof postinstall !== "string" || !isStandaloneKnarrRestoreCommand(postinstall)) {
    return false;
  }

  delete scripts["postinstall"];
  // Clean up empty scripts object
  if (Object.keys(scripts).length === 0) {
    delete pkg["scripts"];
  }
  await atomicWriteFile(pkgPath, JSON.stringify(pkg, null, detectJsonIndent(content)) + "\n");
  return true;
}

/**
 * Auto-initialize a consumer project: create .knarr/state.json,
 * add .knarr/ to .gitignore, add postinstall script.
 */
export async function ensureConsumerInit(
  projectDir: string,
  pm: PackageManager,
): Promise<void> {
  const knarrDir = getConsumerKnarrDir(projectDir);
  const statePath = getConsumerStatePath(projectDir);

  if (!(await exists(statePath))) {
    await ensureDir(knarrDir);
    await writeConsumerState(projectDir, {
      version: "1",
      packageManager: pm,
      role: "consumer",
      links: ownRecord(),
    });
  } else {
    // Ensure PM is recorded
    const state = await readConsumerState(projectDir);
    if (!state.packageManager) {
      state.packageManager = pm;
      state.role = state.role ?? "consumer";
      await writeConsumerState(projectDir, state);
    }
  }

  const gitignorePath = join(projectDir, ".gitignore");
  await ensureGitignore(gitignorePath);

  await ensureRestoreHook(projectDir);
}
